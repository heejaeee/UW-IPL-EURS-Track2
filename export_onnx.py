"""Rebuild the static submitted graph from local weights, without downloads."""
from pathlib import Path
import json, random
import numpy as np
import torch

def main(model_dir, out_onnx):
    import onnx
    from onnxsim import simplify
    from src.model import TTA
    root = Path(model_dir).resolve().parent
    random.seed(42); np.random.seed(42); torch.manual_seed(42)
    torch.set_num_threads(2)
    cfg = json.loads((root / 'config.json').read_text())
    model = TTA(root)
    state = torch.load(root / cfg['candidates'][cfg['candidate']], map_location='cpu', weights_only=True)
    model.load_state_dict(state, strict=True)
    model.eval().requires_grad_(False)
    with torch.inference_mode():
        torch.onnx.export(model, torch.zeros(1,3,1024,1024), str(out_onnx),
            opset_version=17, input_names=['image'], output_names=['restored_image','seg_logits'],
            do_constant_folding=True)
    graph, equivalent = simplify(onnx.load(str(out_onnx)), check_n=1)
    if not equivalent: raise RuntimeError('ONNX simplification equivalence check failed')
    # Torch 2.4 / onnxsim assigns an autogenerated _v_N name to this folded
    # reshape constant; Torch 2.7 retains its original Concat output name.
    # Preserve the historical tensor name without changing any tensor or op.
    for node in graph.graph.node:
        if node.op_type == 'Reshape' and node.output[0] == '/restorer/Reshape_output_0':
            old_name = node.input[1]
            canonical = '/restorer/Concat_5_output_0'
            if old_name != canonical:
                value = next(t for t in graph.graph.initializer if t.name == old_name)
                if not np.array_equal(onnx.numpy_helper.to_array(value), [1, 3, -1]):
                    raise RuntimeError('Unexpected restorer reshape constant')
                value.name = canonical
                for op in graph.graph.node:
                    for i, name in enumerate(op.input):
                        if name == old_name: op.input[i] = canonical
                for value_info in graph.graph.value_info:
                    if value_info.name == old_name: value_info.name = canonical
    onnx.checker.check_model(graph, full_check=True)
    onnx.save_model(graph, str(out_onnx), save_as_external_data=False)
